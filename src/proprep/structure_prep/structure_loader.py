    @staticmethod
    def _remove_hydrogens_from_structure(structure) -> int:
        """Remove all hydrogen atoms from a BioPython Structure in-place.

        Returns:
            Number of hydrogen atoms removed
        """
        total_removed = 0
        for model in structure:
            for chain in model:
                for residue in list(chain):
                    for atom in list(residue):
                        if atom.element and atom.element.strip().upper() == 'H':
                            residue.detach_child(atom.id)
                            total_removed += 1
        return total_removed

    def _save_hstripped_structure(self, workspace, structure, pdb_file: str):
        """Save H-stripped structure to disk and register in workspace.

        Args:
            workspace: Current workspace
            structure: BioPython Structure object (already H-stripped in-place)
            pdb_file: Original PDB file path (used to derive _noH filename)
        """
        from Bio.PDB import PDBIO

        # Derive output filename: 1ABC.pdb -> 1ABC_noH.pdb
        pdb_path = Path(pdb_file)
        noh_filename = pdb_path.stem + "_noH" + pdb_path.suffix
        noh_path = Path(pdb_path.parent) / noh_filename

        io = PDBIO()
        io.set_structure(structure)
        io.save(str(noh_path))

        workspace = self.update_workspace(workspace, "hstripped_pdb_file", str(noh_path.absolute()))
        workspace = self.update_workspace(workspace, "hstripped_structure", structure)

        self.console.print(f"[grey50]H-stripped structure saved to: {noh_filename}[/grey50]")

    def _handle_hydrogen_removal(self, workspace, structure, pdb_file: str):
        """Prompt for and perform hydrogen removal on a freshly loaded structure.

        Args:
            workspace: Current workspace
            structure: BioPython Structure object (modified in-place if H removed)
            pdb_file: Path to the PDB file (for H++ detection)
        """
        if structure is None:
            return

        # Count hydrogens
        h_count = sum(1 for atom in structure.get_atoms()
                      if atom.element and atom.element.strip().upper() == 'H')

        if h_count == 0:
            return

        # H++ detection: hydrogens were added by the H++ server, keep them
        if _detect_hplusplus_structure(pdb_file):
            self.console.print(
                "\n[cyan]H++ structure detected - hydrogens were added by the H++ server. "
                "Skipping hydrogen removal.[/cyan]"
            )
            workspace = self.update_workspace(workspace, "is_hplusplus_structure", True)
            return

        # Check if decision was already made (e.g., a previous load in this session)
        existing_decision = workspace.get("remove_hydrogens_for_md")

        if existing_decision is True:
            removed = self._remove_hydrogens_from_structure(structure)
            self._save_hstripped_structure(workspace, structure, pdb_file)
            self.console.print(
                f"[green]Removed {removed} hydrogen atom{'s' if removed != 1 else ''} "
                f"(using previous selection)[/green]"
            )
            return
        elif existing_decision is False:
            return

        # First time - prompt the user
        self.console.print(f"\n[bold yellow]Hydrogen Atom Removal[/bold yellow]")
        self.console.print(
            f"This structure contains [bold]{h_count}[/bold] hydrogen atoms. "
            "Hydrogen naming in PDB structures is often inconsistent with force field "
            "expectations. It is recommended to remove them and let tLEaP add them back "
            "with correct naming, positions, and protonation states."
        )

        remove = confirm_with_context(
            processor=self.processor,
            prompt="\nRemove hydrogen atoms?",
            default=True,
            module="Structure Loader",
            description="Remove hydrogen atoms from loaded structure"
        )

        workspace = self.update_workspace(workspace, "remove_hydrogens_for_md", remove)

        if remove:
            removed = self._remove_hydrogens_from_structure(structure)
            self._save_hstripped_structure(workspace, structure, pdb_file)
            self.console.print(
                f"[green]Removed {removed} hydrogen atom{'s' if removed != 1 else ''}[/green]"
            )

