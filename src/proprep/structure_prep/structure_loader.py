    def _batch_download_structures(
        self,
        results: List[PDBSearchResult],
        workspace: Dict[str, Any]
    ) -> Dict[str, Any]:
        """
        Batch download multiple PDB structures with progress indication.

        Args:
            results: List of PDBSearchResult objects to download
            workspace: Current workspace dictionary

        Returns:
            Updated workspace with all downloaded structures
        """
        from rich.progress import Progress, SpinnerColumn, TextColumn, BarColumn
        from datetime import datetime

        fetcher = self._get_pdb_fetcher()
        fetcher_logger = logging.getLogger('proprep.structure_prep.pdb_fetcher')
        original_level = fetcher_logger.level
        fetcher_logger.setLevel(logging.WARNING)

        # Initialize or retrieve existing lists from workspace
        pdb_files = list(workspace.get("rcsb_pdb_files", []))
        structures = list(workspace.get("rcsb_structures", []))
        metadata_list = list(workspace.get("rcsb_metadata_list", []))
        download_info = list(workspace.get("rcsb_download_info", []))

        # Track results
        successful = []
        failed = []

        try:
            with Progress(
                SpinnerColumn(),
                TextColumn("[progress.description]{task.description}"),
                BarColumn(),
                TextColumn("[progress.percentage]{task.percentage:>3.0f}%"),
                console=self.console
            ) as progress:
                task = progress.add_task(
                    f"Downloading {len(results)} structures...",
                    total=len(results)
                )

                for result in results:
                    progress.update(task, description=f"Downloading {result.pdb_id}...")

                    try:
                        pdb_file = fetcher.download_by_id(result.pdb_id)

                        if pdb_file:
                            # Parse structure
                            parser = PDBParser(QUIET=True)
                            structure = parser.get_structure(result.pdb_id, pdb_file)

                            # Extract metadata
                            from proprep.structure_prep.pdb_loader import PDBMetadataExtractor
                            metadata = PDBMetadataExtractor(pdb_file)

                            # Append to lists
                            abs_path = str(Path(pdb_file).absolute())
                            pdb_files.append(abs_path)
                            structures.append(structure)
                            metadata_list.append(metadata)
                            download_info.append({
                                "pdb_id": result.pdb_id,
                                "file_path": abs_path,
                                "downloaded_at": datetime.now().isoformat(),
                                "resolution": result.resolution,
                                "method": result.experimental_method
                            })

                            successful.append(result.pdb_id)
                        else:
                            failed.append(result.pdb_id)

                    except Exception as e:
                        logger.error(f"Error downloading {result.pdb_id}: {e}")
                        failed.append(result.pdb_id)

                    progress.advance(task)

        finally:
            fetcher_logger.setLevel(original_level)

        # Update workspace with lists
        workspace = self.update_workspace(workspace, "rcsb_pdb_files", pdb_files)
        workspace = self.update_workspace(workspace, "rcsb_structures", structures)
        workspace = self.update_workspace(workspace, "rcsb_metadata_list", metadata_list)
        workspace = self.update_workspace(workspace, "rcsb_download_info", download_info)

        # Update single-key values with most recent for backward compatibility
        if successful:
            latest_idx = len(pdb_files) - 1
            workspace = self.update_workspace(workspace, "rcsb_pdb_file", pdb_files[latest_idx])
            workspace = self.update_workspace(workspace, "rcsb_structure", structures[latest_idx])
            workspace = self.update_workspace(workspace, "rcsb_metadata", metadata_list[latest_idx])

        # Display results summary
        self.console.print()
        if successful:
            self.console.print(f"[green]Successfully downloaded {len(successful)} structure(s):[/green]")
            for pdb_id in successful:
                self.console.print(f"  [green]✓ {pdb_id}[/green]")

        if failed:
            self.console.print(f"\n[red]Failed to download {len(failed)} structure(s):[/red]")
            for pdb_id in failed:
                self.console.print(f"  [red]✗ {pdb_id}[/red]")

        return workspace

