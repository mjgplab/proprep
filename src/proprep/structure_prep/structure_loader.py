    @staticmethod
    def _extract_pdb_id_from_filename(pdb_file: str) -> str:
        """Extract PDB ID from filename (e.g., '2O60.pdb' or '2O60_assembly1.pdb' -> '2O60')."""
        if not pdb_file:
            return None
        import re
        basename = Path(pdb_file).stem  # e.g., "2O60_assembly1" or "2O60"
        match = re.match(r'^([A-Za-z0-9]{4})', basename)
        return match.group(1).upper() if match else None

