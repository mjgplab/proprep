    def _parse_multi_selection(
        self,
        selection: str,
        page_results: List[PDBSearchResult]
    ) -> List[PDBSearchResult]:
        """
        Parse multi-selection input and return selected results.

        Supports:
        - Single number: "1"
        - Comma-separated: "1,3,5"
        - Range notation: "1-3"
        - Combined: "1-3,5,7-9"
        - All: "all"

        Args:
            selection: User input string
            page_results: List of results on current page

        Returns:
            List of selected PDBSearchResult objects (empty if invalid input)
        """
        if selection == "all":
            return list(page_results)

        indices = set()
        try:
            parts = selection.split(",")
            for part in parts:
                part = part.strip()
                if "-" in part:
                    # Range notation
                    start, end = part.split("-", 1)
                    start_idx = int(start.strip())
                    end_idx = int(end.strip())
                    for idx in range(start_idx, end_idx + 1):
                        if 1 <= idx <= len(page_results):
                            indices.add(idx)
                else:
                    # Single number
                    idx = int(part)
                    if 1 <= idx <= len(page_results):
                        indices.add(idx)
        except (ValueError, IndexError):
            return []

        if not indices:
            return []

        # Return results in selection order (sorted by index)
        return [page_results[idx - 1] for idx in sorted(indices)]

