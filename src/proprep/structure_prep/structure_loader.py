    def load_structure_interactive(self, workspace: Dict[str, Any] = None) -> Dict[str, Any]:
        """
        Interactive structure loading workflow.

        Shows submenu with four options:
        1. Query Protein Data Bank (RCSB)
        2. Query AlphaFold Database
        3. Query AlphaFill Database
        4. Load local PDB file

        Loops until user selects Cancel, allowing multiple sources to be loaded.
        """
        if workspace is None:
            workspace = self.processor._get_workspace()

        # Loop to allow loading multiple sources without returning to main menu
        while True:
            self.console.print("\n[bold bright_blue]═══ Load Structure - Select Source ═══[/bold bright_blue]\n")

            # Display menu options
            self.console.print("1. Query Protein Data Bank (RCSB)", highlight=False)
            self.console.print("2. Query AlphaFold Database", highlight=False)
            self.console.print("3. Query AlphaFill Database (AlphaFold + ligands/cofactors)", highlight=False)
            self.console.print("4. Load local PDB file", highlight=False)
            self.console.print("5. View local files together (spatial comparison, view-only)", highlight=False)
            self.console.print("6. Cancel\n", highlight=False)

            # Show submenu
            choice = prompt_with_context(
                self.processor,
                prompt="Select source",
                choices=["1", "2", "3", "4", "5", "6"],
                default="1",
                module="Structure Loader",
                description="Select structure source",
                options_map={
                    "1": "Query Protein Data Bank (RCSB)",
                    "2": "Query AlphaFold Database",
                    "3": "Query AlphaFill Database (AlphaFold + ligands/cofactors)",
                    "4": "Load local PDB file",
                    "5": "View local files together (spatial comparison, view-only)",
                    "6": "Cancel"
                }
            )

            if choice == "1":
                workspace = self._load_from_pdb_database(workspace)

            elif choice == "2":
                workspace = self._load_from_alphafold_database(workspace)

            elif choice == "3":
                workspace = self._load_from_alphafill_database(workspace)

            elif choice == "4":
                workspace = self._load_local_file(workspace)

            elif choice == "5":
                self._view_local_files_together()

            else:  # Cancel
                self.console.print("[grey50]Cancelled[/grey50]")
                break

        return workspace

