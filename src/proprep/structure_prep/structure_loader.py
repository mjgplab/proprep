    def _select_pdb_from_uniprot(
        self,
        entry: UniProtEntry,
        workspace: Dict[str, Any]
    ) -> Dict[str, Any]:
        """Interactive selection of PDB structure from UniProt entry."""
        pdb_structures = entry.pdb_ids

        # Sort by resolution (best first), with NMR at end
        def sort_key(pdb):
            res_str = pdb.get('resolution', '-')
            if res_str == '-' or not res_str:
                return (True, 999.0)  # NMR/no resolution at end
            try:
                return (False, float(res_str.split()[0]))  # Extract number from "1.20 A"
            except:
                return (True, 999.0)

        pdb_structures_sorted = sorted(pdb_structures, key=sort_key)

        # Paginate results
        page_size = 20
        current_page = 0
        total_pages = (len(pdb_structures_sorted) + page_size - 1) // page_size

        while True:
            # Calculate page bounds
            start_idx = current_page * page_size
            end_idx = min(start_idx + page_size, len(pdb_structures_sorted))
            page_results = pdb_structures_sorted[start_idx:end_idx]

            # Display table
            self._display_uniprot_pdb_table(
                page_results, entry.protein_name, start_idx, len(pdb_structures_sorted),
                current_page + 1, total_pages
            )

            # Build options
            options = []
            options.append(f"Enter number (1-{len(page_results)}) to select structure")
            if current_page < total_pages - 1:
                options.append("Type 'next' to see next page")
            if current_page > 0:
                options.append("Type 'prev' to see previous page")
            options.append("Type 'cancel' to go back")

            self.console.print("\n[bold]Options:[/bold]")
            for opt in options:
                self.console.print(f"  • {opt}")

            # Get user selection
            selection_raw = prompt_with_context(
                self.processor,
                "\nSelection",
                module="Structure Loader - UniProt PDB Selection",
                description=f"Select PDB structure from UniProt (page {current_page + 1}/{total_pages})"
            )

            selection = selection_raw.strip().lower() if selection_raw else ""

            # Handle selection
            if selection == "next" and current_page < total_pages - 1:
                current_page += 1
            elif selection == "prev" and current_page > 0:
                current_page -= 1
            elif selection == "cancel":
                self.console.print("[grey50]Selection cancelled[/grey50]")
                return workspace
            else:
                # Try to parse as number
                try:
                    choice_num = int(selection)
                    if 1 <= choice_num <= len(page_results):
                        selected_pdb = page_results[choice_num - 1]
                        return self._download_and_load_pdb(selected_pdb['id'], workspace)
                    else:
                        self.console.print(f"[yellow]Please enter a number between 1 and {len(page_results)}[/yellow]")
                except ValueError:
                    self.console.print(f"[yellow]Invalid selection: '{selection}'[/yellow]")

    def _display_uniprot_pdb_table(
        self,
        pdb_structures: List[Dict[str, str]],
        protein_name: str,
        start_idx: int,
        total_count: int,
        current_page: int,
        total_pages: int
    ):
        """Display table of PDB structures from UniProt."""
        self.console.print(f"\n[bold bright_blue]═══ PDB Structures for {protein_name} (Page {current_page}/{total_pages}) ═══[/bold bright_blue]")
        self.console.print(f"[grey50]Showing {start_idx + 1}-{start_idx + len(pdb_structures)} of {total_count}[/grey50]\n")

        # Create table
        table = Table(show_header=True, header_style="bold bright_blue", box=None)
        table.add_column("#", style="grey50", width=4)
        table.add_column("PDB ID", style="bold bright_blue", width=8)
        table.add_column("Method", style="yellow", width=10)
        table.add_column("Resolution", style="green", width=12)
        table.add_column("Chains", style="white", width=20)

        for i, pdb in enumerate(pdb_structures, start=1):
            pdb_id = pdb.get('id', 'N/A')
            method = pdb.get('method', 'Unknown')
            resolution = pdb.get('resolution', '-')
            chains = pdb.get('chains', '')

            # Shorten method names
            if "X-RAY" in method.upper() or "X-ray" in method:
                method = "X-ray"
            elif "NMR" in method.upper():
                method = "NMR"
            elif "ELECTRON" in method.upper() or "EM" in method.upper():
                method = "Cryo-EM"

            table.add_row(str(i), pdb_id, method, resolution, chains)

        self.console.print(table)

    def _load_amber_files(self):
        """Load AMBER topology + coordinates (rst7 or trajectory) into workspace.

        Stores paths in workspace keys so downstream modules (MD Manager,
        QM/MM Preparator) can pick them up:
          - parm7_file: prmtop path (always set)
          - rst7_file + md_structure_pairs: set when an rst7/inpcrd is loaded
          - trajectory_files: list of paths set when trajectory segments are loaded
        """
        from proprep.qmmm_prep.frame_extractor import FrameExtractor

        self.console.print(
            "\n[bold bright_blue]═══ Load AMBER topology & coordinate files ═══[/bold bright_blue]\n"
        )
        self.console.print(
            "[grey50]Loaded files are stored in the workspace for use by the "
            "Molecular Dynamics Manager and QM/MM Preparator.[/grey50]\n"
        )

        workspace = self.processor._get_workspace()
        browser = FrameExtractor(self.processor, workspace)

        # 1. Topology
        try:
            prmtop_path = browser.find_or_browse_file(
                "prmtop", [".prmtop", ".parm7"], "AMBER topology file"
            )
        except FileNotFoundError:
            self.console.print("[yellow]Topology selection cancelled.[/yellow]")
            return
        if not os.path.exists(prmtop_path):
            self.console.print(f"[red]Topology not found: {prmtop_path}[/red]")
            return

        # 2. Coordinate source
        choice = prompt_with_context(
            self.processor,
            "Coordinate source: \\[r]st7/inpcrd or \\[t]rajectory (.nc/.mdcrd/…)",
            choices=["r", "t"],
            default="r",
            module="Structure Loader - Load AMBER files",
            description="Coordinate source type for loaded topology",
            options_map={
                "r": "Single rst7/inpcrd restart/coordinate file",
                "t": "MD trajectory (one or more segments)",
            },
        ).strip().lower()

        if choice.startswith("t"):
            traj_paths: List[str] = []
            while True:
                try:
                    traj_path = browser.find_or_browse_file(
                        "trajectory",
                        [".nc", ".mdcrd", ".crd", ".dcd", ".xtc", ".trr", ".binpos"],
                        "MD trajectory file",
                    )
                except FileNotFoundError:
                    break
                traj_paths.append(traj_path)
                self.console.print(
                    f"  Added: [cyan]{os.path.basename(traj_path)}[/cyan]"
                )
                if not confirm_with_context(
                    self.processor,
                    "Add another trajectory segment?",
                    default=False,
                    module="Structure Loader - Load AMBER files",
                    description="Add another trajectory segment",
                ):
                    break

            if not traj_paths:
                self.console.print("[yellow]No trajectory files selected.[/yellow]")
                return

            workspace.set("parm7_file", prmtop_path)
            workspace.set("trajectory_files", traj_paths)
            self.console.print(
                f"\n[green]✓ Loaded topology + {len(traj_paths)} trajectory segment(s) into workspace[/green]"
            )
            self.console.print(
                "[grey50]Use the Molecular Dynamics Manager (analysis) or QM/MM Preparator to process these files.[/grey50]"
            )
        else:
            try:
                rst7_path = browser.find_or_browse_file(
                    "rst7", [".rst7", ".inpcrd", ".crd"], "AMBER rst7/inpcrd file"
                )
            except FileNotFoundError:
                self.console.print("[yellow]Coordinate selection cancelled.[/yellow]")
                return
            if not os.path.exists(rst7_path):
                self.console.print(f"[red]Coordinates not found: {rst7_path}[/red]")
                return

            workspace.set("parm7_file", prmtop_path)
            workspace.set("rst7_file", rst7_path)

            # Append to md_structure_pairs so MD Manager Step 0 picks it up.
            existing_pairs = workspace.get("md_structure_pairs", []) or []
            pair_name = Path(prmtop_path).stem
            new_entry = {
                "name": pair_name,
                "prmtop": str(prmtop_path),
                "rst7": str(rst7_path),
            }
            # Avoid duplicates on repeated loads
            if not any(
                p.get("prmtop") == new_entry["prmtop"]
                and p.get("rst7") == new_entry["rst7"]
                for p in existing_pairs
            ):
                existing_pairs.append(new_entry)
                workspace.set("md_structure_pairs", existing_pairs)

            self.console.print(
                f"\n[green]✓ Loaded topology + rst7 pair into workspace[/green]"
            )
            self.console.print(
                "[grey50]Use the Molecular Dynamics Manager or QM/MM Preparator to proceed.[/grey50]"
            )

