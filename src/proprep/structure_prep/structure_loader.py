    def _search_uniprot_interactive(self, workspace: Dict[str, Any]) -> Dict[str, Any]:
        """Interactive UniProt search by gene name, protein name, or UniProt ID."""
        self.console.print("\n[bold]Search UniProt Database[/bold]\n")

        # Get search parameters
        query_raw = prompt_with_context(
            self.processor,
            'Enter gene name, protein name, or UniProt ID (e.g., "SOD1", "P00441")',
            module="Structure Loader - UniProt Search",
            description="Enter search query for UniProt"
        )

        query = query_raw.strip() if query_raw else ""

        if not query:
            self.console.print("[yellow]No search query entered[/yellow]")
            return workspace

        organism_raw = prompt_with_context(
            self.processor,
            "Filter by organism? (optional, e.g., human, mouse)",
            default="",
            module="Structure Loader - UniProt Search",
            description="Enter organism filter (optional)"
        )

        organism = organism_raw.strip() if organism_raw else ""

        # Perform search
        self.console.print(f'\n[grey50]Searching UniProt for "{query}"' +
                          (f' in "{organism}"...[/grey50]' if organism else '...[/grey50]'))

        searcher = UniProtSearcher()
        # Get all matching accessions (UniProt API max is 500 per request)
        accessions = searcher.search(query, organism if organism else None, max_results=500)

        if not accessions:
            self.console.print(f"[yellow]No UniProt entries found for '{query}'[/yellow]")
            self.console.print("\n[grey50]Tips:[/grey50]")
            self.console.print("[grey50]  • Try the gene name (e.g., 'SOD1')[/grey50]")
            self.console.print("[grey50]  • Try the full protein name (e.g., 'superoxide dismutase')[/grey50]")
            self.console.print("[grey50]  • Try the UniProt ID (e.g., 'P00441')[/grey50]")
            self.console.print("[grey50]  • Remove or change organism filter[/grey50]")
            return workspace

        # If only one result, use it directly
        if len(accessions) == 1:
            entry = searcher.get_entry(accessions[0])
            if not entry:
                self.console.print(f"[red]Failed to fetch UniProt entry {accessions[0]}[/red]")
                return workspace
        else:
            # Multiple results - let user choose
            entry = self._select_uniprot_entry(searcher, accessions)
            if not entry:
                return workspace

        # Display entry summary
        self._display_uniprot_summary(entry)

        # Offer to view full metadata
        if confirm_with_context(
            self.processor,
            "\nView detailed UniProt metadata?",
            default=True,
            module="Structure Loader - UniProt",
            description="View full UniProt metadata"
        ):
            self._view_uniprot_metadata(entry)

        # Offer to select and download PDB structure
        if entry.pdb_ids:
            self.console.print(f"\n[green]This entry has {len(entry.pdb_ids)} associated PDB structures[/green]")

            if confirm_with_context(
                self.processor,
                "Select a PDB structure to download?",
                default=True,
                module="Structure Loader - UniProt",
                description="Select PDB structure from UniProt"
            ):
                return self._select_pdb_from_uniprot(entry, workspace)
        else:
            self.console.print("\n[yellow]No PDB structures associated with this entry[/yellow]")

        return workspace

    def _select_uniprot_entry(
        self,
        searcher: UniProtSearcher,
        accessions: List[str]
    ) -> Optional[UniProtEntry]:
        """
        Display multiple UniProt results and let user select one.

        Args:
            searcher: UniProtSearcher instance
            accessions: List of UniProt accession IDs

        Returns:
            Selected UniProtEntry or None if cancelled
        """
        self.console.print(f"\n[green]Found {len(accessions)} UniProt entries[/green]\n")

        # Fetch basic info for each entry to display in table
        self.console.print("[grey50]Fetching entry details...[/grey50]")
        entries = []
        for acc in accessions:
            entry = searcher.get_entry(acc)
            if entry:
                entries.append(entry)

        if not entries:
            self.console.print("[red]Failed to fetch entry details[/red]")
            return None

        # Display table of results
        self._display_uniprot_selection_table(entries)

        # Prompt for selection
        while True:
            choice_raw = prompt_with_context(
                self.processor,
                f"Select entry number (1-{len(entries)}) or 'c' to cancel",
                module="Structure Loader - UniProt Selection",
                description="Select UniProt entry to examine"
            )

            choice = choice_raw.strip() if choice_raw else ""

            if choice.lower() == 'c':
                return None

            try:
                idx = int(choice) - 1
                if 0 <= idx < len(entries):
                    return entries[idx]
                else:
                    self.console.print(f"[yellow]Please enter a number between 1 and {len(entries)}[/yellow]")
            except ValueError:
                self.console.print("[yellow]Please enter a valid number or 'c' to cancel[/yellow]")

