    def _display_confidence_map(self, structure):
        """Display color-coded per-residue confidence map with position markers."""
        if not structure:
            return

        self.console.print(f"\n[bold]Per-Residue Confidence Map:[/bold]")
        self.console.print("[grey50]Color legend: [green]Very High (>90)[/green] | [yellow]Confident (70-90)[/yellow] | [dark_orange3]Low (50-70)[/dark_orange3] | [red]Very Low (<50)[/red][/grey50]\n")

        for model in structure:
            for chain in model:
                chain_id = chain.get_id()
                self.console.print(f"[bold]Chain {chain_id}:[/bold]")

                # Get all residues
                residues = list(chain.get_residues())

                # Display in blocks of 60 residues
                BLOCK_SIZE = 60

                for block_start in range(0, len(residues), BLOCK_SIZE):
                    block_end = min(block_start + BLOCK_SIZE, len(residues))

                    # Position numbers line (every 10 residues)
                    pos_line = ""
                    for j in range(block_start, block_end, 10):
                        pos_label = str(j + 10)
                        spaces = 10 - len(pos_label)
                        pos_line += " " * spaces + pos_label
                    self.console.print(pos_line)

                    # Tick marks line
                    tick_line = ""
                    for j in range(block_start, block_end):
                        tick_line += "|" if ((j + 1) % 10) == 0 else " "
                    self.console.print(tick_line)

                    # Colored sequence line
                    seq_line = ""
                    for i in range(block_start, block_end):
                        residue = residues[i]

                        # Get pLDDT from first atom's B-factor
                        atoms = list(residue.get_atoms())
                        if not atoms:
                            seq_line += "X"
                            continue

                        plddt = atoms[0].get_bfactor()
                        resname = residue.get_resname()

                        # Convert 3-letter to 1-letter code
                        aa_code = self._three_to_one(resname)

                        # Color based on pLDDT
                        if plddt > 90:
                            color = "green"
                        elif plddt >= 70:
                            color = "yellow"
                        elif plddt >= 50:
                            color = "dark_orange3"
                        else:
                            color = "red"

                        seq_line += f"[{color}]{aa_code}[/{color}]"

                    self.console.print(seq_line)
                    self.console.print()  # Blank line between blocks

                self.console.print()  # Blank line between chains

    def _three_to_one(self, three_letter: str) -> str:
        """Convert 3-letter amino acid code to 1-letter."""
        aa_dict = {
            'ALA': 'A', 'CYS': 'C', 'ASP': 'D', 'GLU': 'E', 'PHE': 'F',
            'GLY': 'G', 'HIS': 'H', 'ILE': 'I', 'LYS': 'K', 'LEU': 'L',
            'MET': 'M', 'ASN': 'N', 'PRO': 'P', 'GLN': 'Q', 'ARG': 'R',
            'SER': 'S', 'THR': 'T', 'VAL': 'V', 'TRP': 'W', 'TYR': 'Y'
        }
        return aa_dict.get(three_letter, 'X')

