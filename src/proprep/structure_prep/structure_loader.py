    def _download_and_load_pdb(self, pdb_id: str, workspace: Dict[str, Any]) -> Dict[str, Any]:
        """Download and load a PDB structure by ID."""
        # Download using PDB fetcher (suppress INFO logging)
        # Downloads to current directory (project directory)
        fetcher = self._get_pdb_fetcher()
        fetcher_logger = logging.getLogger('proprep.structure_prep.pdb_fetcher')
        original_level = fetcher_logger.level
        fetcher_logger.setLevel(logging.WARNING)

        self.console.print(f"\n[grey50]Downloading {pdb_id}...[/grey50]")

        try:
            pdb_file = fetcher.download_by_id(pdb_id)
        finally:
            fetcher_logger.setLevel(original_level)

        if not pdb_file:
            self.console.print(f"[red]Failed to download PDB {pdb_id}[/red]")
            return workspace

        # Parse structure
        try:
            parser = PDBParser(QUIET=True)
            structure = parser.get_structure(pdb_id, pdb_file)

            # Extract metadata from PDB file
            from proprep.structure_prep.pdb_loader import PDBMetadataExtractor
            metadata = PDBMetadataExtractor(pdb_file)

            # Store in workspace with RCSB-specific keys (absolute paths)
            workspace = self.update_workspace(workspace, "rcsb_pdb_file", str(Path(pdb_file).absolute()))
            workspace = self.update_workspace(workspace, "rcsb_structure", structure)
            workspace = self.update_workspace(workspace, "rcsb_metadata", metadata)

            self.console.print(f"\n[green]✓ Downloaded {pdb_id}[/green]")

            # Show basic metadata automatically
            self._show_basic_pdb_info(pdb_file, pdb_id)

            # Check residue numbering and display warning if needed
            self._check_residue_numbering(structure)

            # Hydrogen removal prompt
            self._handle_hydrogen_removal(workspace, structure, pdb_file)

            return workspace

        except Exception as e:
            self.console.print(f"[red]Error parsing PDB file: {e}[/red]")
            logger.error(f"Error parsing PDB {pdb_id}: {e}")
            return workspace

    def _download_biological_assembly(self, pdb_id: str, workspace: Dict[str, Any]) -> Dict[str, Any]:
        """Download and load a biological assembly from RCSB."""
        fetcher = self._get_pdb_fetcher()

        # Check available assemblies
        self.console.print(f"\n[grey50]Checking available biological assemblies for {pdb_id}...[/grey50]")
        available_assemblies = fetcher.get_available_assemblies(pdb_id)

        if not available_assemblies:
            self.console.print(f"[yellow]No biological assemblies available for {pdb_id}[/yellow]")
            self.console.print("[grey50]Falling back to asymmetric unit...[/grey50]")
            return self._download_and_load_pdb(pdb_id, workspace)

        # Show available assemblies
        if len(available_assemblies) == 1:
            assembly_num = available_assemblies[0]
            self.console.print(f"[green]Found 1 biological assembly[/green]")
        else:
            self.console.print(f"\n[green]Found {len(available_assemblies)} biological assemblies:[/green]")
            for num in available_assemblies:
                self.console.print(f"  {num}. Assembly {num}")

            # Let user choose
            choices = [str(n) for n in available_assemblies]
            assembly_choice = prompt_with_context(
                self.processor,
                "Select assembly number",
                choices=choices,
                default="1",
                module="Structure Loader - RCSB",
                description="Select biological assembly number"
            )
            assembly_num = int(assembly_choice)

        # Download the assembly
        self.console.print(f"\n[grey50]Downloading biological assembly {assembly_num}...[/grey50]")

        fetcher_logger = logging.getLogger('proprep.structure_prep.pdb_fetcher')
        original_level = fetcher_logger.level
        fetcher_logger.setLevel(logging.WARNING)

        try:
            pdb_file = fetcher.download_biological_assembly(pdb_id, assembly_num)
        finally:
            fetcher_logger.setLevel(original_level)

        if not pdb_file:
            self.console.print(f"[red]Failed to download biological assembly[/red]")
            return workspace

        # Parse structure
        try:
            parser = PDBParser(QUIET=True)
            structure = parser.get_structure(f"{pdb_id}_assembly{assembly_num}", pdb_file)

            # Extract metadata from PDB file
            from proprep.structure_prep.pdb_loader import PDBMetadataExtractor
            metadata = PDBMetadataExtractor(pdb_file)

            # Store in workspace with biological_assembly key (this has higher priority than rcsb_pdb_file)
            workspace = self.update_workspace(workspace, "biological_assembly_pdb_file", str(Path(pdb_file).absolute()))
            workspace = self.update_workspace(workspace, "biological_assembly_structure", structure)
            workspace = self.update_workspace(workspace, "biological_assembly_metadata", metadata)

            # Also store as rcsb for compatibility
            workspace = self.update_workspace(workspace, "rcsb_pdb_file", str(Path(pdb_file).absolute()))
            workspace = self.update_workspace(workspace, "rcsb_structure", structure)
            workspace = self.update_workspace(workspace, "rcsb_metadata", metadata)

            self.console.print(f"\n[green]✓ Downloaded biological assembly {assembly_num} for {pdb_id}[/green]")

            # Show basic info
            self._show_basic_pdb_info(pdb_file, pdb_id)

            # Count chains in assembly
            num_chains = len(list(structure.get_chains()))
            num_atoms = len(list(structure.get_atoms()))
            self.console.print(f"[cyan]Assembly contains {num_chains} chains, {num_atoms:,} atoms[/cyan]")

            # Check residue numbering
            self._check_residue_numbering(structure)

            # Hydrogen removal prompt
            self._handle_hydrogen_removal(workspace, structure, pdb_file)

            return workspace

        except Exception as e:
            self.console.print(f"[red]Error parsing biological assembly: {e}[/red]")
            logger.error(f"Error parsing biological assembly {pdb_id}.{assembly_num}: {e}")
            return workspace

