def _detect_hplusplus_structure(filename: str) -> bool:
    """Detect if a PDB file was generated by the H++ server."""
    try:
        with open(filename, 'r') as f:
            for line in f:
                if line.startswith('REMARK'):
                    if 'biophysics.cs.vt.edu/H++' in line or 'h++ server' in line.lower():
                        return True
                elif line.startswith(('ATOM', 'HETATM')):
                    break
    except Exception as e:
        logger.warning(f"Error detecting H++ structure: {e}")
    return False


