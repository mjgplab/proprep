@dataclass
class BuilderState:
    """
    The state of an MDIN file being constructed.

    Tracks all configured values and provides methods for manipulation.
    """

    title: str = "AMBER MD input generated by ProPrep"
    entries: dict[str, dict[str, Any]] = field(default_factory=dict)
    # entries["cntrl"]["nstlim"] = 500000, etc.

    def set(self, key: str, value: Any, section: str = "cntrl") -> None:
        """Set a keyword value."""
        if section not in self.entries:
            self.entries[section] = {}
        self.entries[section][key.lower()] = value

    def unset(self, key: str, section: str = "cntrl") -> None:
        """Remove a keyword value."""
        if section in self.entries:
            self.entries[section].pop(key.lower(), None)
            # Remove empty sections
            if not self.entries[section]:
                del self.entries[section]

    def get(self, key: str, section: str = "cntrl") -> Any | None:
        """Get a keyword value."""
        return self.entries.get(section, {}).get(key.lower())

    def has(self, key: str, section: str = "cntrl") -> bool:
        """Check if a keyword is set."""
        return key.lower() in self.entries.get(section, {})

    def active_sections(self) -> list[str]:
        """Get sections that have values set."""
        return [s for s, e in self.entries.items() if e]

    def count_in_section(self, section: str) -> int:
        """Count keywords set in a section."""
        return len(self.entries.get(section, {}))

    def count_in_category(self, section: str, category: str, db: KeywordDB) -> int:
        """Count keywords set in a category."""
        count = 0
        for kw in db.by_category(category):
            if kw.section.lower() == section.lower():
                if self.has(kw.name, section):
                    count += 1
        return count

    def all_entries(self) -> list[tuple[str, str, Any]]:
        """Get all (section, key, value) tuples."""
        result = []
        for section, entries in self.entries.items():
            for key, value in entries.items():
                result.append((section, key, value))
        return result

    def clear(self) -> None:
        """Clear all entries."""
        self.entries.clear()

    def copy(self) -> "BuilderState":
        """Create a copy of this state."""
        new_state = BuilderState(title=self.title)
        for section, entries in self.entries.items():
            new_state.entries[section] = dict(entries)
        return new_state


